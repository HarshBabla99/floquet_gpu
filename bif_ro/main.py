import numpy as np
import floquet as flq
import argparse
import os

from params import *
from bif_ro_model import *

#######################################################################################
def main(parent_path = None, disp_path = None, mode='initial', freq_idx = None):

    #====#
    # Compare the uncoupled transmon params to expected vals
    #====#
    H0_t, n_t, eye_t = tmon(**params)

    E_ge = np.real(H0_t[1, 1] - H0_t[0, 0]) / tpi   # GHz
    E_ef = np.real(H0_t[2, 2] - H0_t[1, 1]) / tpi   # GHz

    expected_freq = np.sqrt(8 * params['EJ'] * params['EC']) / tpi
    expected_anharm = -params['EC'] / tpi

    print('Tmon value             | Numerical  | Expected')
    print(f'Frequency (GHz)        | {E_ge:.6f}   | {expected_freq:.6f}')
    print(f'Anharmonicity (GHz)    | {E_ef - E_ge:.6f}  | {expected_anharm:.6f}')

    #====#
    # Compare the full system to the expected values
    #====#
    model = BifurcationROModel(**params)

    # Diagonalize for one of the omega_r's
    # Let's assume we've only got one 
    test_idx = 0
    evals = model.undriven_evals[test_idx]
    assgn_idxs = model.assignment_idxs[test_idx]

    # Get the indices for the first few states
    idx_00, idx_10 = assgn_idxs[0, 0], assgn_idxs[1, 0]
    idx_01, idx_11 = assgn_idxs[0, 1], assgn_idxs[1, 1]
    print(f" idx_10 = {idx_10}\n idx_01 = {idx_01} \n idx_11 = {idx_11}")

    # Compare the energies to the expected vals
    target_omega_r = params['omega_r_values'][test_idx]
    dressed_omega_q, dressed_omega_r, dressed_alpha_q, dressed_Kerr, dressed_chi = model.dressed_parameters[test_idx]

    print( 'Energy   | Numerical (GHz) | Expected (GHz)')
    print(f'omega_q  | {dressed_omega_q/tpi:.6f}      | {E_ge:.6f}')
    print(f'alpha_q  | {dressed_alpha_q/tpi:.6f}      | {-(E_ef - E_ge):.6f}')
    print(f'omega_r  | {dressed_omega_r/tpi:.6f}      | {target_omega_r/tpi:.6f}')
    print(f'Kerr     | {dressed_Kerr/tpi:.6f}      | {params["K"]/tpi:.6f}')
    print(f'chi      | {dressed_chi/tpi:.6f}      | {params["chi"]/tpi:.6f}')
    
    # Find chi
    def dispersive_shifts(evals, g_mat, omega):
        num_states = len(evals)
        chi_mat = np.zeros((num_states, num_states))
        for l in range(num_states):
            for k in range(num_states):
                Delta = evals[l] - evals[k] - omega
                if Delta != 0:
                    chi_mat[l, k] = abs(g_mat[l, k]) ** 2 / Delta
        chi_vec = np.zeros(num_states)
        for l in range(num_states):
            for k in range(num_states):
                chi_vec[l] += chi_mat[l, k] - chi_mat[k, l]
        return chi_vec
    
    evals_t = np.real(np.diag(H0_t.full()))
    g_mat = model.g_optimized[test_idx] * n_t.full()
    bare_omega_r = model.omega_r_optimized[test_idx]

    chi_levels = dispersive_shifts(evals_t, g_mat, bare_omega_r)
    expected_chi_perturbative = -(chi_levels[1] - chi_levels[0]) / tpi

    print('chi (GHz)                   | value')
    print(f'target (params.py)          | {params["chi"] / tpi:.6f}')
    print(f'numerical (exact diag)      | {dressed_chi/tpi:.6f}')
    print(f'perturbative (multi-level)  | {expected_chi_perturbative:.6f}')
    
    #====#
    # Run Floquet
    #====#
    opts = flq.Options(fit_cutoff=8)

    # Everything the model knows except the operators, plus the state indices we
    # actually track. FloquetAnalysis writes this to params_<mode>.npy.
    model_data = model.data_to_save() | {
        'state_indices': [idx_00, idx_10, idx_01, idx_11],
    }

    flq_analy = flq.FloquetAnalysis(model = model, 
                                    state_indices = model_data['state_indices'], 
                                    init_data_to_save = model_data,
                                    options = opts)

    if mode == 'initial':
        os.makedirs(parent_path, exist_ok=True)

        # currently this just saves the undriven_evecs, but could save more if needed.
        for name, array in model.arrays_to_save().items():
            np.save(f'{parent_path}/{name}.npy', array)

        result = flq_analy.run(parent_path, 'initial')
    else:

        state_indices = model_data['state_indices']
        displaced_state = flq.DisplacedStateFit(
            omega_d_values=model.omega_d_values,
            drive_amplitudes=model.drive_amplitudes,
            bare_states=model.bare_state_array()[:, state_indices, :],
            state_indices=state_indices,
            options=opts,
        )

        # Get the saved exponent_pairs and poly_terms (generated by displaced.py)
        # These should be across the whole freq range
        # Then we can filter for our particular one.
        exponent_pairs = np.load(f'{disp_path}/exponent_pairs.npy')
        poly_terms = np.load(f'{disp_path}/poly_terms.npy')
        
        if freq_idx is not None:
            poly_terms = poly_terms[freq_idx:freq_idx+1, ...]

        displaced_state.exponent_pairs = exponent_pairs
        displaced_state.poly_terms = poly_terms
        
        # Load coefficients
        coeffs = np.load(f'{disp_path}/coeffs.npy')
        result = flq_analy.run(parent_path, 'final', displaced_state, coeffs)
    
    return result

#######################################################################################
if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Bifurcation Readout")
    parser.add_argument("--freq_idx", default=None, type=int, help="Index of the drive frequency")
    parser.add_argument("--parent_path", default='out/', type=str, help="Parent path for the output")
    parser.add_argument("--disp_path", default=None, type=str, help="Path for the coefficients needed for the final run")
    parser.add_argument("--mode", default='initial', type=str, help="Mode (initial or final)")
    parser_args = vars(parser.parse_args())

    # Select the one frequency if specified, else select all of them
    if parser_args['freq_idx'] is not None:
        omega_r = params['omega_r_values'][parser_args['freq_idx']]
        params['omega_r_values'] = np.array([omega_r])
        filename_freq = f'{omega_r/tpi:.3f}'
    else:
        filename_freq = 'all'

    parent_path = parser_args['parent_path'] + f'freq_{filename_freq}/'

    main(parent_path, parser_args['disp_path'], parser_args['mode'],
         parser_args['freq_idx'])
